  (function generateAdvancedExamples() {
    const advanced = { N3: 1, N2: 1, N1: 1 };
    const tagged = new Set(EXAMPLES.map((e) => e.introduces).filter(Boolean));
    ALL_CARDS.forEach((c) => {
      if (c.type !== "vocab" || !advanced[c.level]) return;
      if (tagged.has(c.id)) return;
      let ex = (c.ex || [])[0];
      if (!ex) return;
      // inline examples may be [text, tr] arrays OR {text, tr} objects
      if (Array.isArray(ex)) ex = { text: ex[0], tr: ex[1] };
      if (!ex.text) return;
      EXAMPLES.push({ text: ex.text, tr: ex.tr || "", req: [], introduces: c.id });
    });
  })();

